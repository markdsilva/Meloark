test('sort menu, touch actions, compact controls and reduced motion remain usable', async ({ page }) => {
  await load(page, true)
  await page.getByRole('button', { name: 'Sort tracks', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Title', exact: true }).click()
  await page.getByRole('button', { name: 'Actions for A', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: /Move up/ })).toHaveAttribute('aria-disabled', 'true')
  await page.keyboard.press('Escape')
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.getByRole('button', { name: 'Actions for A', exact: true }).click()
    const menu = page.getByRole('menu', { name: 'Track actions' }); await expect(menu).toBeVisible()
    const bounds = await menu.boundingBox(); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await page.keyboard.press('Escape')
    if (width < 768) expect((await page.getByRole('button', { name: 'Actions for A', exact: true }).boundingBox())!.width).toBeGreaterThanOrEqual(44)
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.locator('.app').evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  await page.mouse.move(0, 0)
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).focus()
  await expect(page.getByRole('tooltip')).toContainText('Collapse sidebar')
  await page.screenshot({ path: 'test-results/polished-desktop.png' })
})
