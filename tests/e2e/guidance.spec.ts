test('context menus preserve groups, support keyboard navigation, and restore focus', async ({ page }) => {
  await load(page, true)
  await page.getByRole('checkbox', { name: 'Select A', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Select C', exact: true }).check()
  const row = page.locator('.track-row').filter({ has: page.getByRole('button', { name: 'Play A', exact: true }) })
  await row.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Remove from playlist', exact: true }).click()
  await expect(page.locator('.track-title strong')).toHaveText(['B'])
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await row.focus(); await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menu', { name: 'Track actions' })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Play', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Remove from playlist', exact: true })).toBeFocused()
  await page.keyboard.press('Escape'); await expect(row).toBeFocused()
})
test('app removal survives refresh and reload and hidden playlists can be restored', async ({ page }) => {
  await load(page, true)
  await page.getByRole('button', { name: 'Actions for playlist List.m3u8', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Remove from app', exact: true }).click()
  await expect(page.locator('.playlist-row')).toHaveCount(0)
  await page.getByRole('button', { name: 'Refresh library', exact: true }).click()
  await expect(page.locator('.playlist-row')).toHaveCount(0)
  await page.waitForTimeout(400); await page.reload()
  await expect(page.getByText('Reconnect your music', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Manage playlists', exact: true }).click()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await expect(page.locator('.playlist-row')).toHaveCount(1)
})
